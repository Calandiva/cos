function forMission(m) {
  var prod = G.PROD.get(m.ch);
  var ch = CH[m.ch] || {};
  var seen = {}, tips = [];
  m.must.concat(m.bonus || []).forEach(function (c) {
    var key = c.k === 'yield' ? 'yield_' : c.k;
    if (seen[key] || !ADVICE[key]) return;
    seen[key] = 1;
    tips.push({ ko: G.MISS.label(c, m.ch), msg: ADVICE[key](prod.kind) });
  });
  var terms = (ch.terms || []).map(function (t) { return G.GLOSS.find(t); }).filter(Boolean);
  return {
    intro: TYPE_INTRO[m.type] || '',
    hook: ch.hook || '',
    tips: tips,
    skeleton: ch.skeleton || [],
    watch: ch.watch || [],
    terms: terms
  };
}

G.GUIDE = { CH: CH, forMission: forMission, ADVICE: ADVICE };
